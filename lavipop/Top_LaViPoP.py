def discover_languages() -> list[dict]:
    global available_languages

    result = []

    if LANGUAGE_DIR.exists():
        for path in sorted(LANGUAGE_DIR.glob("*.png")):
            match = LANG_RE.match(path.name)
            if not match:
                continue

            result.append(
                {
                    "code": match.group("lang"),
                    "datecode": match.group("datecode"),
                    "filename": path.name,
                    "path": path,
                }
            )

    available_languages = [item["code"] for item in result]
    return result


def image_dimensions(path: Path, fallback=(32, 32)) -> tuple[int, int]:
    image = cv2.imread(str(path), cv2.IMREAD_UNCHANGED)

    if image is None:
        return fallback

    h, w = image.shape[:2]
    h = min(200, h)
    w = min(200, w)
    return int(w), int(h)


