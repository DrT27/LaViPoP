@app.callback(
    Output("landscape-background-view", "src"),
    Output("landscape-background-view", "className"),
    Output("landscape-background-view", "style"),
    Output("first-frame-view-landscape", "style"),
    Input("preview-meta-store", "data"),
    Input("preview-frame-store", "data"),
    Input("cb_use_static_background", "checked"),
)
def update_landscape_preview(
    meta,
    frame_src,
    static_background_checked,
):
    hidden = {"display": "none"}

    if not meta or not frame_src:
        return no_update, "landscape-background-frame", hidden, hidden

    source_w = int(meta["original_width"])
    source_h = int(meta["original_height"])

    source_is_portrait = source_h > source_w

    # --------------------------------------------------------------
    # LANDSCAPE SOURCE -> LANDSCAPE TARGET
    #
    # Mirrors processor:
    # scale=increase + crop to 1920x1080
    # --------------------------------------------------------------
    if not source_is_portrait:
        source_ratio = source_w / source_h
        target_ratio = LANDSCAPE_W / LANDSCAPE_H

        needs_background = abs(source_ratio - target_ratio) > 0.001

        if needs_background:
            foreground_style = {
                "display": "block",
                "objectFit": "contain",
                "objectPosition": "center center",
                "background": "transparent",
            }
            if static_background_checked:
                background_src = "/vidpop-static-background"
                background_class = "landscape-background-frame"
            else:
                background_src = frame_src
                background_class = (
                    "landscape-background-frame "
                    "landscape-background-blurred"
                )
            background_style = {
                "display": "block",
            }
            return (
                background_src,
                background_class,
                background_style,
                foreground_style,
            )
        else:
            foreground_style = {
                "display": "block",
                "objectFit": "cover",
                "objectPosition": "center center",
            }
            return (
                no_update,
                "landscape-background-frame",
                hidden,
                foreground_style,
            )



    # --------------------------------------------------------------
    # PORTRAIT SOURCE -> LANDSCAPE TARGET
    #
    # Mirrors processor:
    # full portrait foreground at complete target height
    # over blurred or static 16:9 background.
    # --------------------------------------------------------------
    foreground_style = {
        "display": "block",
        "objectFit": "contain",
        "objectPosition": "center center",
        "background": "transparent",
    }

    if static_background_checked:
        background_src = "/vidpop-static-background"
        background_class = "landscape-background-frame"
    else:
        background_src = frame_src
        background_class = (
            "landscape-background-frame "
            "landscape-background-blurred"
        )

    background_style = {
        "display": "block",
    }

    return (
        background_src,
        background_class,
        background_style,
        foreground_style,
    )


