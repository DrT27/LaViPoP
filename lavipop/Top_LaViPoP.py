def cleanup_completed_jobs() -> int:
    """Remove expired, completed output jobs only.

    A finished job has lavipop_results.zip. Unfinished jobs (including live
    FFmpeg jobs) are deliberately excluded, even if processing takes hours.
    Uploaded sources, cache, logos, and application files are never touched.
    """
    if RETENTION_HOURS == 0:
        return 0

    deadline = time.time() - RETENTION_HOURS * 3600
    removed = 0
    for job_dir in OUTPUT_DIR.iterdir():
        if not job_dir.is_dir():
            continue
        # Only operate on UUID-named job directories generated by this app.
        try:
            if job_dir.name != uuid.UUID(hex=job_dir.name).hex:
                continue
        except ValueError:
            continue

        zip_file = job_dir / "lavipop_results.zip"
        try:
            if not zip_file.is_file() or zip_file.stat().st_mtime >= deadline:
                continue
            shutil.rmtree(job_dir)
            removed += 1
            print(f"LaViPoP cleanup: removed expired job {job_dir.name}", flush=True)
        except OSError as exc:
            print(f"LaViPoP cleanup: unable to remove {job_dir}: {exc}", flush=True)
    return removed


def _periodic_cleanup() -> None:
    # Daemon thread: doesn't prevent server shutdown.
    while True:
        try:
            cleanup_completed_jobs()
        except OSError as exc:
            print(f"LaViPoP cleanup error: {exc}", flush=True)
        time.sleep(CLEANUP_INTERVAL_MINUTES * 60)


# Run once at startup and periodically while the web application is running.
# Cleanup is deliberately scoped to completed jobs: incomplete jobs need an
# independent recovery policy rather than a potentially unsafe age-based delete.
if RETENTION_HOURS > 0:
    threading.Thread(target=_periodic_cleanup, name="lavipop-cleanup", daemon=True).start()

