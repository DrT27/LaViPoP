def read_first_frame(video_path: Path):
    cap = cv2.VideoCapture(str(video_path))

    try:
        ok, frame = cap.read()

        if not ok or frame is None:
            return None, None

        original_h, original_w = frame.shape[:2]

        # Preview may NEVER exceed 800 x 600.
        # Never upscale smaller frames.
        scale = min(
            1.0,
            800.0 / original_w,
            600.0 / original_h,
        )

        capped_w = max(1, int(round(original_w * scale)))
        capped_h = max(1, int(round(original_h * scale)))

        # Resize the actual frame
        if scale < 1.0:
            frame = cv2.resize(
                frame,
                (capped_w, capped_h),
                interpolation=cv2.INTER_AREA,
            )

        # Encode the resized frame
        ok, encoded = cv2.imencode(".jpg", frame)

        if not ok:
            return None, None

        b64 = base64.b64encode(encoded.tobytes()).decode("ascii")
        src = f"data:image/jpeg;base64,{b64}"

        meta = {
            "original_width": int(original_w),
            "original_height": int(original_h),
            "capped_width": capped_w,
            "capped_height": capped_h,
        }

        return src, meta

    finally:
        cap.release()

def percent_to_px_old(value_percent: float, frame_size: int, w_width:int=None) -> int:
    """Convert an orientation-independent 0..100 percentage to pixels."""



    value_percent = max(0.0, min(100.0, float(value_percent)))

    if w_width is not None:
        return frame_size - int(round(frame_size * value_percent / 100.0) - w_width)
    else:
        return int(round(frame_size * value_percent / 100.0))

def percent_to_px(value_percent, frame_size, w_width=None):
    value_percent = max(0.0, min(100.0, float(value_percent)))

    offset = round(frame_size * value_percent / 100.0)

    if w_width is not None:
        return frame_size - offset - w_width

    return offset

